"""AG-SEC-001: hardcoded API keys, tokens and private keys."""

from __future__ import annotations

import math
import re
from collections.abc import Iterable, Iterator
from dataclasses import dataclass
from typing import ClassVar

from apkguard.context import ApkContext, StringItem
from apkguard.model import Category, Finding, Location, RuleMeta, Severity
from apkguard.rules._util import iter_methods
from apkguard.rules.base import Rule


@dataclass(frozen=True)
class SecretPattern:
    name: str
    regex: re.Pattern[str]
    severity: Severity


PATTERNS: tuple[SecretPattern, ...] = (
    SecretPattern(
        "Private key",
        re.compile(r"-----BEGIN (?:RSA |EC |DSA |OPENSSH |ENCRYPTED )?PRIVATE KEY-----"),
        Severity.CRITICAL,
    ),
    SecretPattern("AWS access key ID", re.compile(r"\b(?:AKIA|ASIA)[0-9A-Z]{16}\b"), Severity.HIGH),
    SecretPattern(
        "GitHub token",
        re.compile(r"\b(?:gh[pousr]_[A-Za-z0-9]{36}|github_pat_\w{60,})"),
        Severity.HIGH,
    ),
    SecretPattern("Slack token", re.compile(r"\bxox[abprs]-[0-9A-Za-z-]{10,}"), Severity.HIGH),
    SecretPattern(
        "Slack webhook",
        re.compile(r"https://hooks\.slack\.com/services/T[0-9A-Z]+/B[0-9A-Z]+/[0-9A-Za-z]+"),
        Severity.HIGH,
    ),
    SecretPattern(
        "Stripe secret key", re.compile(r"\b(?:sk|rk)_live_[0-9A-Za-z]{20,}"), Severity.CRITICAL
    ),
    SecretPattern(
        "OpenAI API key", re.compile(r"\bsk-(?:proj-)?[A-Za-z0-9_-]{32,}"), Severity.HIGH
    ),
    SecretPattern("Anthropic API key", re.compile(r"\bsk-ant-[A-Za-z0-9_-]{32,}"), Severity.HIGH),
    SecretPattern(
        "SendGrid API key",
        re.compile(r"\bSG\.[A-Za-z0-9_-]{22}\.[A-Za-z0-9_-]{43}\b"),
        Severity.HIGH,
    ),
    SecretPattern("Twilio API key", re.compile(r"\bSK[0-9a-fA-F]{32}\b"), Severity.MEDIUM),
    SecretPattern("Google API key", re.compile(r"\bAIza[0-9A-Za-z_-]{35}\b"), Severity.MEDIUM),
    SecretPattern(
        "JSON Web Token",
        re.compile(r"\beyJ[A-Za-z0-9_-]{10,}\.eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}"),
        Severity.MEDIUM,
    ),
    SecretPattern(
        "Credentials in URL",
        re.compile(r"\b[a-z][a-z0-9+.-]*://[^/\s:@]{3,}:[^/\s:@]{3,}@[\w.-]+"),
        Severity.HIGH,
    ),
)

# Resource names that hint at a secret, checked together with an entropy threshold.
SECRET_NAME = re.compile(
    r"(api[_-]?key|apikey|secret|token|passw(or)?d|client[_-]?secret|auth[_-]?key|private[_-]?key)",
    re.IGNORECASE,
)
# Keys generated by the google-services Gradle plugin; they are meant to ship in the APK.
GOOGLE_SERVICES_RESOURCES = {
    "google_api_key",
    "google_crash_reporting_api_key",
    "firebase_database_url",
    "google_app_id",
    "gcm_defaultSenderId",
    "default_web_client_id",
}
_PLACEHOLDER = re.compile(r"(your|example|xxxx|changeme|placeholder|todo|dummy|<|\$\{)", re.I)


def shannon_entropy(value: str) -> float:
    if not value:
        return 0.0
    counts = {c: value.count(c) for c in set(value)}
    return -sum((n / len(value)) * math.log2(n / len(value)) for n in counts.values())


def redact(secret: str) -> str:
    if len(secret) <= 8:
        return "*" * len(secret)
    return f"{secret[:4]}...{secret[-2:]} (len {len(secret)})"


class HardcodedSecretRule(Rule):
    meta = RuleMeta(
        id="AG-SEC-001",
        title="Hardcoded secret",
        severity=Severity.HIGH,
        category=Category.SECRETS,
        description=(
            "An API key, access token, private key or credential is embedded in the app's code, "
            "resources or assets. APKs are trivially unpacked, so anything shipped inside them "
            "must be considered public."
        ),
        remediation=(
            "Revoke and rotate the exposed credential. Keep secrets on your backend and have the "
            "app obtain short-lived, user-scoped tokens at runtime. For keys that must ship in the "
            "client (e.g. Google Maps), restrict them by package name and signing certificate in "
            "the provider console. Use a secrets plugin to keep keys out of source control."
        ),
        references=(
            "https://developer.android.com/privacy-and-security/risks/hardcoded-cryptographic-secrets",
            "https://cloud.google.com/docs/authentication/api-keys#securing",
            "https://mas.owasp.org/MASTG/tests/android/MASVS-STORAGE/MASTG-TEST-0001/",
        ),
        cwe="CWE-798",
        masvs="MASVS-STORAGE-1",
    )
    default_options: ClassVar[dict[str, object]] = {"entropy_threshold": 3.5, "min_length": 16}

    def check(self, ctx: ApkContext) -> Iterable[Finding]:
        threshold = float(str(self.options["entropy_threshold"]))
        min_len = self.option_int("min_length")
        reported: set[tuple[str, str]] = set()
        for item in self._strings(ctx):
            matched = False
            for pattern in PATTERNS:
                for match in pattern.regex.finditer(item.value):
                    secret = match.group(0)
                    key = (pattern.name, secret)
                    matched = True
                    if key in reported:
                        continue
                    reported.add(key)
                    severity = pattern.severity
                    note = ""
                    if (
                        pattern.name == "Google API key"
                        and item.symbol in GOOGLE_SERVICES_RESOURCES
                    ):
                        severity = Severity.LOW
                        note = (
                            " This key comes from google-services.json and is expected in the "
                            "APK; make sure it is restricted to your app's package and signature."
                        )
                    yield self.finding(
                        f"{pattern.name} found in {item.file}"
                        f"{f' ({item.symbol})' if item.symbol else ''}.{note}",
                        Location(item.file, item.symbol),
                        evidence=redact(secret),
                        severity=severity,
                        secret_type=pattern.name,
                    )
            if matched or not item.symbol or not item.file.startswith("res/"):
                continue
            # Named resource that looks like a secret, e.g. <string name="stripe_secret">...
            name = item.symbol.rsplit("/", 1)[-1]
            value = item.value.strip()
            if (
                name not in GOOGLE_SERVICES_RESOURCES
                and SECRET_NAME.search(name)
                and len(value) >= min_len
                and " " not in value
                and not _PLACEHOLDER.search(value)
                and shannon_entropy(value) >= threshold
            ):
                key = ("generic", value)
                if key in reported:
                    continue
                reported.add(key)
                yield self.finding(
                    f"Resource {item.symbol} looks like a hardcoded secret (high-entropy value).",
                    Location(item.file, item.symbol),
                    evidence=redact(value),
                    severity=Severity.MEDIUM,
                    secret_type="Generic secret",
                )

    @staticmethod
    def _strings(ctx: ApkContext) -> Iterator[StringItem]:
        yield from ctx.strings
        for cls, method in iter_methods(ctx):
            for ins in method.instructions:
                if ins.string is not None and len(ins.string) >= 10:
                    yield StringItem(ins.string, cls.source_dex, method.short_name)
